from pathlib import Path

FPC_ROOT = Path(os.environ.get("FPC_ROOT", "/usr/workspace/das9/fpchecker_bf"))
BRANCH_FLIP = FPC_ROOT / "cpu_checking/error_analysis/branch_flip"
BENCH_ROOT = Path(os.environ.get("BENCH_ROOT", BRANCH_FLIP / "benchmarks/nas"))

BENCHES = ["bt", "cg", "ep", "is", "lu", "mg", "sp"]

# benchmark -> source files (relative to the variant dir)
SRCS = {
    "bt": ["bt.c"],
    "cg": ["cg.c"],
    "lu": ["lu.c"],
    "mg": ["mg.c"],
    "sp": ["sp.c"],
    "ep": ["ep.c", "c_randdp.c", "c_print_results.c", "c_timers.c", "wtime.c"],
    "is": ["is.c", "c_print_results.c", "c_timers.c", "wtime.c"],
}

# benchmark -> variant -> extra defines.
#
# BT/CG/LU/SP come from the compile-time switch and need the macro.
# EP is hand-converted but ALSO keyed on WORKING_T (a second, independent
# precision control -- see the note in its tree).
# IS/MG are hand-converted with precision baked into the source: no define,
# and adding one would do nothing.
_SWITCH = {"fp32": "-DNAS_FP32", "fp64": "", "ld": "-DNAS_LD"}
_NONE = {"fp32": "", "fp64": "", "ld": ""}
DEFINES = {
    "bt": _SWITCH, "cg": _SWITCH, "lu": _SWITCH, "sp": _SWITCH,
    "is": _NONE, "mg": _NONE,
    "ep": {"fp32": "-DWORKING_T=float -DWORKING_T_IS_FLOAT=1",
           "fp64": "-DWORKING_T=double",
           "ld":   "-DWORKING_T=long\\ double -DWORKING_T_IS_LD=1"},
}

VARIANTS = {"fp32": "%s_fp32", "fp64": "%s_fp64", "ld": "%s_ld"}

PRECISION_MARKERS = [
    ("single", r"\b(mulss|addss|subss|divss|cvtss2sd)\b"),
    ("double", r"\b(mulsd|addsd|subsd|divsd|cvtsd2ss)\b"),
    ("x87/ld", r"\b(fldt|fstpt|fmulp|faddp|fdivp)\b"),
]

PAIRS = [("fp32_vs_fp64", "fp32", "fp64"), ("fp64_vs_ld", "fp64", "ld")]

SITE_RE = re.compile(
    r"^\[BranchTrace\]\s+(\S+)\s+\(mod\s+(\d+)\):\s+instrumented\s+(\d+)\s+branch sites")

VERIFY_RE = re.compile(r"\b(SUCCESSFUL|UNSUCCESSFUL)\b", re.I)


def _find_brx():
    env = os.environ.get("BRX_ROOT")
    here = Path(__file__).resolve().parent
    cands = ([Path(env)] if env else []) + [
        here / "brtrace", here.parent / "brtrace",
        BRANCH_FLIP / "brtrace",
        FPC_ROOT / "cpu_checking/error_analysis/brtrace",
    ]
    for c in cands:
        if (c / "libBranchTrace_mtu.so").exists():
            return c.resolve()
    for c in cands:
        if c.is_dir():
            return c.resolve()
    return cands[0].resolve()


BRX_ROOT = _find_brx()
