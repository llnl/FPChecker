#!/usr/bin/env python3
"""
run_nas_brtrace.py

Build the three precision variants of each NAS benchmark under the brtrace
pass, run each once, and diff two pairs to produce the ground-truth
branch-flip census:

    fp32 vs fp64      does single precision flip branches relative to double?
    fp64 vs ld        is double itself oracle-stable against long double?

fp64 is built and run ONCE per benchmark per optimisation level and its trace
feeds both diffs, so this costs three builds and three runs per level.

Place in: branch_flip/experiments/gt_experiments/

    ./run_nas_brtrace.py                        # all 7, -O0
    ./run_nas_brtrace.py -b lu sp bt ep         # the ones with non-zero GT
    ./run_nas_brtrace.py --opt O0 O2
    ./run_nas_brtrace.py --dry-run
    ./run_nas_brtrace.py --skip-build --skip-run    # re-diff existing traces

Layout produced (one subtree per benchmark per optimisation level):

    nas/
      results/
        bt/O0/  builds/  traces/  fp32_vs_fp64/  fp64_vs_ld/  summary.txt
        cg/O0/  ...
      build/
        bt/O0/bt_fp32/  bt/O0/bt_fp64/  bt/O0/bt_ld/  ...

DIFFERENCES FROM THE LULESH AND AMG HARNESSES
---------------------------------------------
  * NAS is C, so the frontend is clang, not clang++, and there is no name
    mangling to undo.
  * SEVEN benchmarks rather than one target. Each is built and diffed
    independently; a failure in one does not stop the others.
  * MIXED PROVENANCE. The trees do not all select precision the same way:
      - BT, CG, LU, SP were produced by the compile-time switch, so they
        take -DNAS_FP32 / -DNAS_LD and share one source.
      - EP, IS, MG are the hand-converted trees: precision is baked into the
        SOURCE, and EP additionally needs -DWORKING_T=<type>.
    DEFINES below encodes this per benchmark. Getting it wrong does not fail
    the build -- it silently produces two variants at the same precision,
    which reads as "zero flips" rather than as an error. The precision check
    is what catches that.
  * NO RUN ARGUMENTS. Problem size is compiled in via npbparams.h, so the
    binaries take no arguments. Class is S everywhere except CG, which is W.
  * THREE BINARY NAMING CONVENTIONS in the existing trees -- bt, ep_fp32,
    mg_longdouble. We ignore them: every variant is compiled here to the same
    name (<bench>.brx), directly, not through the tree's Makefile.

WHY NOT USE THE TREES' MAKEFILES
--------------------------------
Matched-build discipline requires the three variants to differ ONLY in
precision. The hand-converted trees carry per-variant CFLAGS that differ in
more than that (LU fp32/fp64 use -Wall -Wno-unused where ld uses -w; EP uses
-O2 where BT uses -O3). Driving clang directly makes one flag set
authoritative for all three, so site ids correspond.

STALE ARTEFACTS
---------------
The hand-converted trees still contain .brx / .brsites / .brmods files from an
earlier census. Sources are copied into build/ and those files are deleted
before compiling, so a stale trace can never be read as current.

EXISTING GROUND TRUTH
---------------------
A previous census over the OLD trees recorded:
    LU=11  SP=10  BT=10  EP=1  CG=0  MG=0  IS=0   (fp32 vs fp64, site level)
Four of the seven trees have since been regenerated by the compile-time
switch, so a fresh census need not reproduce those exactly. Any difference is
worth resolving before either number is published -- same physics, different
source structure.
"""

