RESULT_ROOT = WORK_ROOT / "results"


def log(m=""):
    print(m, flush=True)


def die(m):
    sys.stderr.write("ERROR: %s\n" % m)
    sys.exit(1)


def human(n):
    for u in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or u == "TB":
            return "%.1f %s" % (n, u)
        n /= 1024.0


def sh(cmd, cwd=None, env=None, logfile=None, dry=False, timeout=None):
    log("    $ %s" % cmd)
    if dry:
        return 0, ""
    t0 = time.time()
    try:
        p = subprocess.run(cmd, cwd=str(cwd) if cwd else None, env=env,
                           shell=True, stdout=subprocess.PIPE,
                           stderr=subprocess.STDOUT, text=True,
                           errors="replace", timeout=timeout)
        rc, out = p.returncode, p.stdout
    except subprocess.TimeoutExpired as e:
        rc, out = 124, (e.output or "") + "\n[TIMEOUT after %ss]" % timeout
    dt = time.time() - t0
    if logfile:
        Path(logfile).write_text("$ %s\n(cwd %s)\n\n%s\n[exit %d in %.1fs]\n"
                                 % (cmd, cwd or os.getcwd(), out, rc, dt))
    log("      -> exit %d in %.1fs" % (rc, dt))
    return rc, out


def parse_site_counts(text):
    out = {}
    for line in text.splitlines():
        m = SITE_RE.match(line.strip())
        if m:
            out[os.path.basename(m.group(1))] = (int(m.group(2)),
                                                 int(m.group(3)))
    return out


# --------------------------------------------------------------- build

def build(bench, variant, opt, cfg, outdir, dry=False):
    src = BENCH_ROOT / bench / (VARIANTS[variant] % bench)
    dst = BUILD_ROOT / bench / opt / (VARIANTS[variant] % bench)
    if not src.is_dir():
        return None, {}, "no source tree at %s" % src
    missing = [s for s in SRCS[bench] if not (src / s).exists()]
    if missing:
        return None, {}, "%s missing: %s" % (src, ", ".join(missing))

    if not dry:
        dst.parent.mkdir(parents=True, exist_ok=True)
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
        # Drop prebuilt binaries and the stale side tables that ship in the
        # hand-converted trees, so nothing uninstrumented or out of date can
        # be picked up.
        for pat in ("*.o", "*.brsites", "*.brmods", "*.brx"):
            for j in dst.glob(pat):
                j.unlink()
        for j in dst.iterdir():
            if j.is_file() and os.access(j, os.X_OK) and j.suffix == "":
                j.unlink()

    binname = "%s.brx" % bench
    cmd = "%s %s %s %s %s %s -lm -o %s" % (
        cfg["cc"], cfg["cflags"](opt), cfg["ccflags"],
        DEFINES[bench].get(variant, ""), " ".join(SRCS[bench]),
        cfg["runtime"], binname)
    cmd = re.sub(r"\s+", " ", cmd)
    logf = outdir / "builds" / ("%s.build.log" % variant)
    rc, out = sh(cmd, cwd=dst, logfile=logf, dry=dry)
    if dry:
        return dst / binname, {}, None
    if rc != 0 or not (dst / binname).exists():
        tail = out.strip().splitlines()[-12:]
        for line in tail:
            log("      %s" % line[:180])
        return None, {}, "build failed (see %s)" % logf

    counts = parse_site_counts(out)
    if not counts:
        return None, {}, ("no [BranchTrace] banner -- the pass did not run "
                          "(see %s)" % logf)
    total = sum(n for _, n in counts.values())
    log("      instrumented %d sites across %d TU(s)" % (total, len(counts)))
    (outdir / "builds" / ("%s.build_info.txt" % variant)).write_text(
        "benchmark   = %s\nvariant     = %s\nopt         = -%s\n"
        "cc          = %s\ncflags      = %s\nccflags     = %s\n"
        "defines     = %s\nsrcs        = %s\nsrc_tree    = %s\n"
        "build_dir   = %s\nsites_total = %d\nsites_by_tu = %s\n"
        "openmp      = disabled; brtrace needs a single-threaded run or the\n"
        "              two traces cannot be walked in lock-step.\n"
        % (bench, variant, opt, cfg["cc"], cfg["cflags"](opt), cfg["ccflags"],
           DEFINES[bench].get(variant) or "(none)", " ".join(SRCS[bench]),
           src, dst, total,
           ", ".join("%s=%d" % (m, counts[m][1]) for m in sorted(counts))))
    return dst / binname, counts, None


def precision_check(binaries, variants, allow, dry=False):
    """Distinct arithmetic per variant.

    A matched-build check proves the variants share branch STRUCTURE. It
    cannot prove they differ in ARITHMETIC -- and if a precision define is
    missed they will not. That failure is invisible everywhere else: builds
    succeed, site counts agree, traces are the same length, and both diffs
    report zero flips, which reads as a clean result.
    """
    if dry or len(binaries) < 2 or not shutil.which("objdump"):
        return []
    profiles, problems = {}, []
    for v in variants:
        b = binaries.get(v)
        if not b or not Path(b).exists():
            continue
        p = subprocess.run("objdump -d %s" % shlex.quote(str(b)), shell=True,
                           text=True, stdout=subprocess.PIPE,
                           stderr=subprocess.DEVNULL, errors="replace")
        profiles[v] = tuple(len(re.findall(pat, p.stdout))
                            for _, pat in PRECISION_MARKERS)
        log("      %-5s %s" % (v, "  ".join(
            "%s=%-7d" % (PRECISION_MARKERS[i][0], profiles[v][i])
            for i in range(3))))
    for a in profiles:
        for b in profiles:
            if a < b and profiles[a] == profiles[b]:
                problems.append("%s and %s emit identical arithmetic" % (a, b))
    if "fp32" in profiles and profiles["fp32"][0] == 0:
        problems.append("fp32 emits no single-precision arithmetic")
    if "ld" in profiles and profiles["ld"][2] == 0:
        problems.append("ld emits no x87 instructions")
    for p in problems:
        log("      *** %s" % p)
    return problems


def check_matched(counts_by_variant, variants):
    if len(counts_by_variant) < 2:
        return []
    mods = set()
    for v in counts_by_variant:
        mods |= set(counts_by_variant[v])
    bad = []
    for mod in sorted(mods):
        vals = {counts_by_variant[v][mod][1]
                for v in variants
                if mod in counts_by_variant.get(v, {})}
        if len(vals) > 1:
            bad.append("%s: %s" % (mod, sorted(vals)))
    return bad


SITE_LINE_RE = re.compile(
    r"^\s+(\S.*?)\s+\(([\d,]+) flips"
    r"(?: of ([\d,]+) executions)?"
    r"(?:, first @ event#([\d,]+))?\)\s*$")


def extract_sites(text):
    out = []
    for line in text.splitlines():
        m = SITE_LINE_RE.match(line)
        if m:
            out.append({"loc": m.group(1).strip(),
                        "flips": int(m.group(2).replace(",", "")),
                        "executions": (int(m.group(3).replace(",", ""))
                                       if m.group(3) else None),
                        "first": (int(m.group(4).replace(",", ""))
                                  if m.group(4) else None)})
    return out


def extract_headline(text):
    got = []

    def find(pat, label, fmt=None):
        m = re.search(pat, text, re.M)
        if m:
            got.append((label, fmt(m) if fmt else m.group(1)))

    find(r"^\s*lock-step compared\s+([\d,]+) events\s+\(([\d.]+)% of longer",
         "adjudicated events",
         lambda m: "%s (%s%% of longer)" % (m.group(1), m.group(2)))
    find(r"^\s*unadjudicated\s+([\d,]+) events", "unadjudicated events")
    find(r"^\s*cause: (.+)$", "cause")
    find(r"^\s*TP\s+sites that flipped at least once\s+(\S+)", "TP sites")
    find(r"^\s*TN\s+sites executed, never flipped\s+(\S+)", "TN sites")
    find(r"^\s*DEAD\s+instrumented, never executed\s+(\S+)", "DEAD sites")
    find(r"^\s*TOTAL sites instrumented\s+(\S+)", "sites instrumented")
    return got


# --------------------------------------------------- one benchmark, one opt

def run_bench(bench, opt, args, cfg, dry=False):
    outdir = RESULT_ROOT / bench / opt
    (outdir / "builds").mkdir(parents=True, exist_ok=True)
    (outdir / "traces").mkdir(parents=True, exist_ok=True)

    log("-" * 70)
    log("  %s  -%s" % (bench.upper(), opt))
    variants = args.variants
    binaries, counts_by_variant, vinfo = {}, {}, {}
    warnings = []

    if args.skip_build:
        for v in variants:
            binaries[v] = (BUILD_ROOT / bench / opt /
                           (VARIANTS[v] % bench) / ("%s.brx" % bench))
    else:
        for v in variants:
            log("    build %s" % v)
            b, c, err = build(bench, v, opt, cfg, outdir, dry=dry)
            if err:
                log("      SKIP %s: %s" % (bench, err))
                return None
            binaries[v] = b
            if c:
                counts_by_variant[v] = c
                vinfo[v] = {"sites_total": sum(n for _, n in c.values())}
        bad = check_matched(counts_by_variant, variants)
        if bad:
            msg = "site counts differ across variants: %s" % "; ".join(bad)
            if args.allow_site_mismatch:
                warnings.append(msg)
                log("      WARNING: %s" % msg)
            else:
                log("      *** %s -- site ids will not correspond" % msg)
                return None
        else:
            log("      matched-build ok")
        log("    precision check")
        probs = precision_check(binaries, variants,
                                args.allow_same_precision, dry)
        if probs and not args.allow_same_precision:
            log("      *** variants are not at distinct precisions; skipping")
            return None
        warnings += probs

    traces = {v: outdir / "traces" / ("%s_%s.out" % (bench, v))
              for v in variants}
    if not args.skip_run:
        for v in variants:
            binp = Path(binaries[v])
            if not dry and not binp.exists():
                log("      SKIP: %s missing" % binp)
                return None
            env = os.environ.copy()
            env["OMP_NUM_THREADS"] = "1"
            env["BRTRACE_OUT"] = str(traces[v])
            cmd = "%s./%s.brx" % ((args.launcher + " ") if args.launcher
                                  else "", bench)
            log("    run %s" % v)
            rc, out = sh(cmd, cwd=binp.parent, env=env,
                         logfile=outdir / "builds" / ("%s.run.log" % v),
                         dry=dry, timeout=args.timeout)
            if not dry:
                if rc != 0:
                    log("      *** run failed (exit %d)" % rc)
                    return None
                m = VERIFY_RE.search(out)
                verdict = m.group(1).upper() if m else "?"
                sz = traces[v].stat().st_size if traces[v].exists() else 0
                log("      verification=%s  %s (%s events)"
                    % (verdict, human(sz), "{:,}".format(sz // 12)))
                vinfo.setdefault(v, {}).update(
                    {"verification": verdict, "bytes": sz, "events": sz // 12})
    else:
        for v in variants:
            if not dry and traces[v].exists():
                sz = traces[v].stat().st_size
                vinfo.setdefault(v, {}).update({"bytes": sz,
                                                "events": sz // 12})

    records = []
    for label, a, b in PAIRS:
        if label not in args.pairs or a not in variants or b not in variants:
            continue
        pdir = outdir / label
        pdir.mkdir(parents=True, exist_ok=True)
        report, csv = pdir / "report.txt", pdir / "flips.csv"
        sites_txt = pdir / "sites.txt"
        mods = BUILD_ROOT / bench / opt / (VARIANTS[b] % bench)
        cmd = ("python3 %s %s %s --mods %s --csv %s --report %s --sites-txt %s"
               % (shlex.quote(str(cfg["diff"])), shlex.quote(str(traces[a])),
                  shlex.quote(str(traces[b])), shlex.quote(str(mods)),
                  shlex.quote(str(csv)), shlex.quote(str(report)),
                  shlex.quote(str(sites_txt))))
        if args.fast:
            cmd += " --fast"
        log("    diff %s" % label)
        rc, out = sh(cmd, logfile=pdir / "diff.log", dry=dry)
        if dry:
            continue
        if rc not in (0, 1):
            log("      *** diff failed (exit %d) -- see %s"
                % (rc, pdir / "diff.log"))
            continue
        sites = extract_sites(out)
        log("      -> %d flips @ %d loc"
            % (sum(s["flips"] for s in sites), len(sites)))
        records.append({"benchmark": bench, "opt": opt, "label": label,
                        "a": a, "b": b, "report": str(report),
                        "headline": extract_headline(out), "sites": sites,
                        "warnings": warnings})

    if dry:
        return None
    lines = ["NAS %s -- brtrace dual-trajectory ground-truth census"
             % bench.upper(),
             "(-%s, single-threaded, class from npbparams.h)" % opt,
             "scope: %s" % cfg["scope"], ""]
    for v in sorted(vinfo):
        lines.append("  %-5s verification=%-13s %s events"
                     % (v, vinfo[v].get("verification", "?"),
                        "{:,}".format(vinfo[v].get("events", 0))))
    lines.append("")
    for r in records:
        lines.append("%s  (%s vs %s)" % (r["label"], r["a"], r["b"]))
        lines.append("    %d flips @ %d loc"
                     % (sum(s["flips"] for s in r["sites"]), len(r["sites"])))
        for k, v in r["headline"]:
            lines.append("    %-24s %s" % (k, v))
        for s in r["sites"]:
            lines.append("      %8d  %s" % (s["flips"], s["loc"]))
        lines.append("")
    if warnings:
        lines.append("WARNINGS")
        for w in warnings:
            lines.append("  " + w)
        lines.append("")
    (outdir / "summary.txt").write_text("\n".join(lines) + "\n")
    (outdir / "summary.json").write_text(
        json.dumps({"benchmark": bench, "opt": opt, "variants": vinfo,
                    "pairs": records}, indent=2, default=str))
    return records


def main():
    global BRX_ROOT, BENCH_ROOT, WORK_ROOT, BUILD_ROOT, RESULT_ROOT
    ap = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-b", "--benchmarks", nargs="+", default=BENCHES,
                    choices=BENCHES)
    ap.add_argument("--opt", nargs="+", default=["O0"],
                    choices=["O0", "O1", "O2", "O3"])
    ap.add_argument("--brx", default=str(BRX_ROOT))
    ap.add_argument("--bench", default=str(BENCH_ROOT))
    ap.add_argument("--work", default=str(WORK_ROOT))
    ap.add_argument("--cc", default="clang")
    ap.add_argument("--ccflags", default="-I. -std=c99 -w")
    ap.add_argument("--variants", nargs="+", default=["fp32", "fp64", "ld"],
                    choices=["fp32", "fp64", "ld"])
    ap.add_argument("--pairs", nargs="+",
                    default=["fp32_vs_fp64", "fp64_vs_ld"],
                    choices=["fp32_vs_fp64", "fp64_vs_ld"])
    ap.add_argument("--launcher", default="")
    ap.add_argument("--timeout", type=int, default=3600,
                    help="per-run timeout in seconds (instrumented NAS runs "
                         "are much slower than bare ones)")
    ap.add_argument("--all-branches", action="store_true")
    ap.add_argument("--fast", action="store_true")
    ap.add_argument("--skip-build", action="store_true")
    ap.add_argument("--skip-run", action="store_true")
    ap.add_argument("--allow-site-mismatch", action="store_true")
    ap.add_argument("--allow-same-precision", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    BRX_ROOT = Path(args.brx).resolve()
    BENCH_ROOT = Path(args.bench).resolve()
    WORK_ROOT = Path(args.work).resolve()
    BUILD_ROOT = WORK_ROOT / "build"
    RESULT_ROOT = WORK_ROOT / "results"
    dry = args.dry_run

    plugin = BRX_ROOT / "libBranchTrace_mtu.so"
    runtime = BRX_ROOT / "brtrace_runtime_mtu.o"
    diff = BRX_ROOT / "tools" / "brtrace_diff_mtu.py"
    for f in (plugin, runtime, diff):
        if not f.exists():
            die("brtrace incomplete: missing %s\n"
                "       Build it: cd %s && ./build_mtu.sh" % (f, BRX_ROOT))

    fp_only = not args.all_branches

    def cflags(opt):
        # -brtrace-fp-only is a cl::opt inside the plugin, so it exists only
        # once the .so has been dlopened. -fpass-plugin alone is too late:
        # clang parses -mllvm in ExecuteCompilerInvocation but does not load
        # pass plugins until the backend runs. -Xclang -load goes through the
        # FrontendOpts::Plugins path, which IS dlopened before -mllvm parsing.
        # Both flags are needed, with the same path, so dlopen returns one
        # handle and the option registers once.
        base = "-%s -g -fpass-plugin=%s" % (opt, plugin)
        if fp_only:
            base += " -Xclang -load -Xclang %s -mllvm -brtrace-fp-only" % plugin
        return base

    cfg = {"cc": args.cc, "ccflags": args.ccflags, "cflags": cflags,
           "runtime": str(runtime), "diff": diff, "plugin": str(plugin),
           "scope": ("FP-CONTROLLED branches (-brtrace-fp-only)" if fp_only
                     else "ALL conditional branches")}

    BUILD_ROOT.mkdir(parents=True, exist_ok=True)
    RESULT_ROOT.mkdir(parents=True, exist_ok=True)

    log("NAS / brtrace   benchmarks: %s   opt: %s"
        % (" ".join(args.benchmarks), " ".join(args.opt)))
    log("  scope: %s" % cfg["scope"])
    log("  brx:   %s" % BRX_ROOT)
    log("  bench: %s" % BENCH_ROOT)
    log("  work:  %s" % WORK_ROOT)
    log("  NOTE:  BT/CG/LU/SP take -DNAS_FP32/-DNAS_LD; EP takes "
        "-DWORKING_T=...;")
    log("         IS/MG bake precision into the source and take no define.")
    if dry:
        log("  MODE:  DRY RUN")
    log()

    allrecs = []
    for opt in args.opt:
        for b in args.benchmarks:
            r = run_bench(b, opt, args, cfg, dry=dry)
            if r:
                allrecs += r
    if dry:
        log("dry run complete")
        return 0
    if not allrecs:
        log("No results produced.")
        return 1

    log("=" * 70)
    log("all results")
    log("=" * 70)
    log("  %-4s %-4s %-14s %8s %6s  %s"
        % ("bench", "opt", "pair", "flips", "sites", "TP/TN/DEAD"))
    for r in allrecs:
        h = dict(r["headline"])
        log("  %-4s %-4s %-14s %8d %6d  %s/%s/%s"
            % (r["benchmark"], r["opt"], r["label"],
               sum(s["flips"] for s in r["sites"]), len(r["sites"]),
               h.get("TP sites", "?"), h.get("TN sites", "?"),
               h.get("DEAD sites", "?")))
    log("\nresults under %s/<bench>/<opt>/" % RESULT_ROOT)
    log("\nPrevious census over the OLD trees, for comparison:")
    log("  LU=11  SP=10  BT=10  EP=1  CG=0  MG=0  IS=0  (fp32-vs-fp64 sites)")
    log("  BT/CG/LU/SP have since been regenerated by the compile-time")
    log("  switch, so differences there are worth resolving before use.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
